-- App Pet - schema Supabase (Postgres). Chạy trong SQL Editor, THEO THỨ TỰ 001 -> 002 -> 003.
-- Catalog tĩnh (wiki) nằm trong app (SQLite), không có trên server.
-- Khác schema v2 cũ: users -> profiles (gắn auth.users); thời gian là timestamptz; image_uri -> image_url;
-- gallery_images.image_url -> image_path (đường dẫn trong bucket gallery, hoặc URL tuyệt đối nếu là ảnh người dùng; v6 thêm thumb_path ở 005);
-- recognition_results có thêm user_id; messages có changed_at (để đồng bộ tin sửa/xóa); bỏ CHECK mâu thuẫn
-- "source_type=USER phải có contributor_id" vì xung đột với ON DELETE SET NULL.

-- ============================== BẢNG ==============================
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text,
  avatar_url text,
  role text not null default 'USER' check (role in ('USER','ADMIN')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists profiles_username_key on public.profiles (lower(username));

create table if not exists public.pet_types (
  id integer primary key,
  name text not null unique,
  description text,
  icon_url text
);

create table if not exists public.breeds (
  id integer primary key,
  pet_type_id integer not null references public.pet_types(id),
  name text not null,
  name_vi text,
  description text,
  origin_country text,
  image_url text,
  unique (pet_type_id, name),
  unique (id, pet_type_id)
);

create table if not exists public.breed_aliases (
  id integer generated by default as identity primary key,
  breed_id integer not null references public.breeds(id) on delete cascade,
  alias text not null,
  unique (breed_id, alias)
);

create table if not exists public.pets (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  pet_type_id integer not null references public.pet_types(id),
  breed_id integer,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  gender text check (gender in ('Đực','Cái')),
  birth_date date,
  color text,
  weight numeric(6,2) check (weight is null or weight > 0),
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (breed_id, pet_type_id) references public.breeds(id, pet_type_id)
);
create index if not exists idx_pets_user on public.pets(user_id);
create index if not exists idx_pets_breed on public.pets(breed_id);

create table if not exists public.pet_images (
  id bigint generated always as identity primary key,
  pet_id bigint not null references public.pets(id) on delete cascade,
  image_url text not null,
  is_main boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists idx_pet_images_pet on public.pet_images(pet_id);
create unique index if not exists uq_pet_images_main on public.pet_images(pet_id) where is_main;

create table if not exists public.recognition_results (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  pet_image_id bigint references public.pet_images(id) on delete cascade,
  detected_pet_type_id integer references public.pet_types(id),
  detected_breed_id integer,
  confidence real,
  model_name text,
  raw_label text,
  result_json jsonb,
  created_at timestamptz not null default now(),
  foreign key (detected_breed_id, detected_pet_type_id) references public.breeds(id, pet_type_id)
);

create table if not exists public.gallery_images (
  id bigint generated always as identity primary key,
  pet_type_id integer references public.pet_types(id),
  breed_id integer,
  source_type text not null check (source_type in ('API','USER','ADMIN')),
  external_id text,
  pet_image_id bigint references public.pet_images(id) on delete cascade,
  contributor_id uuid references public.profiles(id) on delete set null,
  status text not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED')),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  reject_reason text,
  image_path text not null,
  width integer,
  height integer,
  title text,
  description text,
  source_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (breed_id, pet_type_id) references public.breeds(id, pet_type_id),
  unique (source_type, external_id)
);
create index if not exists idx_gallery_status_breed on public.gallery_images(status, breed_id, id);
create index if not exists idx_gallery_status_type on public.gallery_images(status, pet_type_id, id);

create table if not exists public.communities (
  id bigint generated by default as identity primary key,
  pet_type_id integer references public.pet_types(id),
  created_by uuid references public.profiles(id) on delete set null,
  name text not null,
  description text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.community_members (
  community_id bigint not null references public.communities(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'MEMBER' check (role in ('MEMBER','MOD','ADMIN')),
  status text not null default 'ACTIVE' check (status in ('ACTIVE','MUTED','BANNED')),
  muted_until timestamptz,
  joined_at timestamptz not null default now(),
  primary key (community_id, user_id)
);
create index if not exists idx_members_user on public.community_members(user_id);

create table if not exists public.messages (
  id bigint generated always as identity primary key,
  community_id bigint not null references public.communities(id) on delete cascade,
  sender_id uuid references public.profiles(id) on delete set null,   -- NULL = tin hệ thống (Trợ lý Pet)
  content text check (content is null or char_length(content) <= 2000),
  image_url text,
  message_type text not null default 'TEXT' check (message_type in ('TEXT','IMAGE','SYSTEM')),
  created_at timestamptz not null default now(),
  changed_at timestamptz not null default now(),
  is_deleted boolean not null default false,
  deleted_at timestamptz,
  deleted_by uuid references public.profiles(id) on delete set null,
  delete_reason text
);
create index if not exists idx_messages_comm_id on public.messages(community_id, id);
create index if not exists idx_messages_comm_changed on public.messages(community_id, changed_at);

create table if not exists public.message_reports (
  id bigint generated always as identity primary key,
  message_id bigint not null references public.messages(id) on delete cascade,
  reporter_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  reason text not null check (reason in ('SPAM','INAPPROPRIATE','HARASSMENT','PRIVACY','OTHER')),
  detail text,
  status text not null default 'PENDING' check (status in ('PENDING','VIOLATION','DISMISSED')),
  handled_by uuid references public.profiles(id) on delete set null,
  handled_at timestamptz,
  action_taken text check (action_taken is null or action_taken in ('NONE','DELETED_MESSAGE','MUTED_USER','BANNED_USER')),
  created_at timestamptz not null default now(),
  unique (message_id, reporter_id)
);
create index if not exists idx_reports_status on public.message_reports(status, created_at);
